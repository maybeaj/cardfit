/**
 * 마이데이터 CSV의 `merchant_category`(19종)를 앱 카테고리로 옮기는 표.
 *
 * 앱 카테고리는 v0.4 프로토타입 기준본의 카테고리 목록에서만 고른다 (`D-011`) —
 * 입력 화면의 카테고리 선택지와 결과 배분표의 행 이름이 같아야 사용자가 대조할 수 있다.
 *
 * CSV에 없는 카테고리(예식·백화점·간편결제 등)는 여기 두지 않는다.
 * 미래지출 입력에서 사용자가 직접 고를 수 있고, 과거 소비에는 나타나지 않기 때문이다.
 */

/** v0.4 프로토타입 s3 화면의 카테고리 선택지. 이 목록 밖의 값을 만들지 않는다. */
export const APP_CATEGORIES = [
  '여행',
  '주유',
  '교통',
  '쇼핑',
  '음식/배달',
  '통신',
  '카페',
  '구독',
  '전 가맹점',
  '간편결제',
  '편의점',
  '마트',
  '생활',
  '백화점',
  '가전/가구',
  '예식',
  '기타',
] as const

export type AppCategory = (typeof APP_CATEGORIES)[number]

/**
 * CSV 업종 → 앱 카테고리.
 *
 * 묶는 기준은 "카드 혜택 조건이 같은 묶음인가"다. 카드사 약관이 `외식`과 `배달음식`을
 * 따로 구분하지 않고 함께 묶는 경우가 많아 `음식/배달` 하나로 합친다.
 * 반대로 `편의점`과 `마트`는 약관에서 별도 한도가 붙는 경우가 많아 나눠 둔다.
 */
export const CSV_CATEGORY_MAP: Record<string, AppCategory> = {
  대중교통: '교통',
  편의점: '편의점',
  '카페/커피': '카페',
  외식: '음식/배달',
  배달음식: '음식/배달',
  온라인쇼핑: '쇼핑',
  '의류/패션': '쇼핑',
  대형마트: '마트',
  '구독/OTT': '구독',
  '구독/커머스': '구독',
  '구독/음악': '구독',
  통신비: '통신',
  주유: '주유',
  '여행/숙박': '여행',
  '가전/전자': '가전/가구',
  '뷰티/드럭': '생활',
  '병원/약국': '생활',
  미용실: '생활',
  '문화/여가': '기타',
}

/**
 * 표에 없는 업종은 `기타`로 보낸다.
 *
 * 조용히 버리지 않는 이유 — 거래를 누락시키면 과거 소비 합계가 줄어들고,
 * 그 합계가 결론 배너의 비교 기준선이라 차액이 틀어진다 (`T26`).
 * 금액을 지어내지 않으면서 총액을 보존하는 유일한 방법이 `기타`로 모으는 것이다.
 */
export function toAppCategory(csvCategory: string): AppCategory {
  return CSV_CATEGORY_MAP[csvCategory] ?? '기타'
}
